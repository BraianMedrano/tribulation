#!/usr/bin/env python3
"""Generate art/glyphs/threat-tier-16.glyph — the dark red smoke threat cue.

Six 16px frames of a smoke puff that swells, darkens and thins out as it ages.
The particle picks a frame from its age (setSpriteFromAge), so the frames ship
split as threat_tier_0..5.png and the particle JSON lists them in order. With
"frames: split" the renderer expands the "ships:" path, threat_tier.png, into
one numbered file per frame, so the base name itself is never written.

Each frame is three overlapping soft blobs whose radius grows with age; a fixed
integer hash roughens the edge and, past the first third of the life, drops
pixels so the puff thins out instead of only fading. The hash is deterministic,
so re-running this script always emits the same grid.

Run from the repository root:  python3 art/glyphs/threat-tier-16.gen.py
"""
import math
from pathlib import Path

SIZE = 16
FRAMES = 6
OUT = Path(__file__).with_suffix("").with_suffix(".glyph")

# Hot rust core to cold soot edge: Tribulation's ember ramp down, then the
# shared smoke neutral for the two coldest steps.
RAMP = [
    ("a", "tribulation.ember-1", "hot rust core"),
    ("b", "tribulation.ember-2", "deep red"),
    ("c", "tribulation.ember-3", "blood red"),
    ("d", "tribulation.ember-4", "dark maroon"),
    ("e", "smoke-3", "soot"),
    ("f", "smoke-4", "cold soot edge"),
]

MASK = 0xFFFFFFFF


def _i32(v):
    v &= MASK
    return v - (1 << 32) if v >= (1 << 31) else v


def _hash(x, y, k):
    """32-bit integer hash in [0, 1]; mirrors the preview page bit for bit."""
    h = _i32(x * 374761393 + y * 668265263 + k * 982451653)
    u = h & MASK
    h = _i32(u ^ (u >> 13))
    h = _i32((h & MASK) * 1274126177)
    u = h & MASK
    h = _i32(u ^ (u >> 16))
    return (h & MASK) / 4294967295


def frame(k):
    t = k / (FRAMES - 1)
    r = 3.1 + t * 3.9
    rows = []
    for y in range(SIZE):
        row = []
        for x in range(SIZE):
            px, py = x + 0.5, y + 0.5
            d0 = math.hypot(px - 8, py - 8.4) / r
            d1 = math.hypot(px - (8 - r * 0.45), py - (7.2 - t)) / (r * 0.72)
            d2 = math.hypot(px - (8 + r * 0.4), py - (7.6 - t * 0.5)) / (r * 0.66)
            noise = _hash(x, y, k * 7 + 3)
            d = min(d0, d1, d2) + (noise - 0.5) * 0.32
            if d >= 1 or (t > 0.35 and noise < (t - 0.35) * 0.85):
                row.append(".")
                continue
            idx = max(0, min(len(RAMP) - 1, math.floor((d * 0.55 + t * 0.7) * 4.2)))
            row.append(RAMP[idx][0])
        rows.append("".join(row))
    return rows


def main():
    lines = [
        "# tribulation — Threat cue (generic tier-4+): dark red smoke puff, 16px particle.",
        "# GENERATED by threat-tier-16.gen.py — edit the generator, not this grid.",
        "# Six age frames: a small hot rust puff that swells, cools to soot and thins",
        "# out as it rises. The particle selects the frame from its age, so frames ship",
        "# split (threat_tier_0..5.png) and fading is done in code on top.",
        f"size: {SIZE}",
        "kind: particle",
        "frames: split",
        "frametime: 5",
        "ships: src/main/resources/assets/tribulation/textures/particle/threat_tier.png",
        "",
        "legend:",
        "  . transparent",
    ]
    lines += [f"  {ch} {token:<22}# {note}" for ch, token, note in RAMP]
    for k in range(FRAMES):
        lines.append("")
        lines.append(f"# age {k + 1} of {FRAMES}")
        lines.append("frame:")
        lines += ["  " + row for row in frame(k)]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
